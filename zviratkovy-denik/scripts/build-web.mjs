#!/usr/bin/env node
/**
 * Builds the PWA: `expo export --platform web` + offline service worker with a
 * precache manifest of every exported file + SPA fallback for GitHub Pages.
 *
 *   node scripts/build-web.mjs        → ./dist
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(projectRoot, 'dist');

console.log('› expo export --platform web');
execSync('npx expo export --platform web --output-dir dist', {
  cwd: projectRoot,
  stdio: 'inherit',
});

// Inject the PWA wiring into the exported shell ("single" output ignores +html.tsx).
const indexPath = path.join(dist, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
html = html.replace('<html lang="en">', '<html lang="cs">');
html = html.replace(
  /<meta name="viewport"[^>]*\/>/,
  '<meta name="viewport" content="width=device-width, initial-scale=1, shrink-to-fit=no, viewport-fit=cover, user-scalable=no" />'
);
const headExtras = `
    <meta name="theme-color" content="#FFF7EC" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="default" />
    <meta name="apple-mobile-web-app-title" content="Zuzanky deník" />
    <link rel="manifest" href="manifest.webmanifest" />
    <link rel="apple-touch-icon" href="apple-touch-icon.png" />
    <link rel="icon" type="image/png" href="icon-192.png" />
    <style>html,body{background:#FFF7EC;overscroll-behavior-y:none}</style>
    <script>if('serviceWorker' in navigator){window.addEventListener('load',function(){navigator.serviceWorker.register('sw.js').catch(function(){})})}</script>
  </head>`;
html = html.replace('</head>', headExtras);
fs.writeFileSync(indexPath, html);

// Collect every exported file as a relative ./path for the precache list.
const files = [];
function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full);
    else files.push('./' + path.relative(dist, full).split(path.sep).join('/'));
  }
}
walk(dist);

const version = 'zd-' + Date.now().toString(36);
const sw = `// Generated by scripts/build-web.mjs — offline cache for Zuzanky deník.
const CACHE = ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify(['./', ...files.filter((f) => f !== './sw.js')], null, 1)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  if (req.mode === 'navigate') {
    // The app is a single-page app — every navigation serves the cached shell.
    event.respondWith(
      caches.match('./index.html').then((cached) => cached || fetch(req))
    );
    return;
  }
  event.respondWith(
    caches.match(req).then(
      (cached) =>
        cached ||
        fetch(req).then((res) => {
          if (res.ok && new URL(req.url).origin === self.location.origin) {
            const clone = res.clone();
            caches.open(CACHE).then((c) => c.put(req, clone));
          }
          return res;
        })
    )
  );
});
`;

fs.writeFileSync(path.join(dist, 'sw.js'), sw);
// GitHub Pages SPA fallback: unknown paths render the app shell too.
fs.copyFileSync(path.join(dist, 'index.html'), path.join(dist, '404.html'));

console.log(`✓ dist ready — ${files.length} files precached, cache version ${version}`);
